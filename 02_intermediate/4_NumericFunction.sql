-- NUMERIC FUNCTION
-- ROUND FUNCTION-- IT ROUND OFF THE VALUE 

SELECT
	3.516 AS DummyNumber,
	ROUND(3.516, 2) AS Round2,
	ROUND(3.516, 1) AS Round1,
	ROUND(3.516, 0) AS Round0

-- ABS FUNCTION -- ITS ABSOLUTE FUNCTION IT CONVERTS ANY NEGATIVE VALUE INTO POSITIVE VALUE

SELECT 
	-10 AS Negative,
	ABS(-10) AS POSITIVE,
	ABS(10) AS ALREADY_POSITIVE
