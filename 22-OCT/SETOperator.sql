/* SET OPERATORS
UNION - WRITES ALL THE ROWS FROM BOTH THE QUERIES EXCLUDING THE DUPLICATE TABLES
UNION ALL - SAME AS UNION BUT ALLOWS DUPLICATE ROWS ALSO
EXCEPT - IT CONTAINS ALL THE DISTINCT ROWS FROM THE QUERIES ONE SIMILAR TO LEFT ANTI JOIN
INTERSECT - IT IT RETURNS ONLY THE ROWS WHICH ARE COMMAN IN BOTH QUERIES
*/
-- Union
SELECT 
	c.FirstName,
	c.LastName
FROM Sales.Customers c

UNION

SELECT 
	e.FirstName,
	e.LastName
FROM Sales.Employees e
ORDER BY FirstName DESC

-- UNION ALL
SELECT 
	c.FirstName,
	c.LastName
FROM Sales.Customers c

UNION ALL

SELECT 
	e.FirstName,
	e.LastName
FROM Sales.Employees e

-- EXCEPT IT RETURN ALL THE ROWS FROM THE FIRST QUERY WHICH ARE NOT PRESENT IN THE SECOND QUERY I.E. IT RETURN DISTINCT ROWS FROM FIRST QUERY

SELECT 
	c.FirstName,
	c.LastName
FROM Sales.Customers c

EXCEPT

SELECT 
	e.FirstName,
	e.LastName
FROM Sales.Employees e

-- INTERSECT

SELECT 
	c.FirstName,
	c.LastName
FROM Sales.Customers c

INTERSECT

SELECT 
	e.FirstName,
	e.LastName
FROM Sales.Employees e
