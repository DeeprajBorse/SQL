/*
	Business Scenario: Marketing wants to segment customers based on their total spending in the active orders table,
	including customers who have spent $0.

	Task: Find the total sales and order count per customer, including customers who have placed zero orders.

*/

WITH CustomerSpend AS
(
	SELECT 
		CustomerID,
		SUM(Sales) AS total_spent,
		COUNT(OrderID) AS total_orders
	FROM Sales.Orders
	GROUP BY CustomerID
)
SELECT 
	c.CustomerID,
	COALESCE(c.FirstName,'')+' '+COALESCE(c.LastName,'') [Customer Name],
	COALESCE(cs.total_orders, 0) [Total Orders],
	COALESCE(cs.total_spent, 0) [Total Spent]
FROM Sales.Customers c	
LEFT JOIN CustomerSpend cs
ON cs.CustomerID = c.CustomerID

/*
	Business Scenario: HR wants to spotlight the single highest-paid employee in each department without displaying the rest of the team.

	TASK: Find the highest-paid employee in each department.
*/

WITH DeptSalaryRank AS
(
	SELECT 
		EmployeeID,
		CONCAT(FirstName,' ',LastName) EmployeeName,
		Department,
		Salary,
		RANK() OVER(PARTITION BY DEPARTMENT ORDER BY Salary DESC ) Salary_Rank
	FROM Sales.Employees
)
SELECT *
FROM DeptSalaryRank
WHERE Salary_Rank = 1

/*
	MULTIPLE STANDALONE CTE

	Business Scenario: Finance wants a side-by-side comparison of how much each customer spent in 2024 (orders_archive) versus 2025 (orders) to measure year-over-year retention.

	TASK: Compare each customer's total spending in 2024 (orders_archive) against their total spending in 2025 (orders),
		showing the net difference.
*/

WITH ActiveSpend AS (
SELECT 
	CustomerID,
	SUM(Sales) total_sales_o
FROM Sales.Orders
GROUP BY CustomerID
)
, ArchiveSpend AS (
SELECT
	CustomerID,
	SUM(Sales) total_sales_oa
FROM Sales.OrdersArchive
GROUP BY CustomerID
)
SELECT 
	c.CustomerID,
	CONCAT(FirstName,' ', LastName) CustomersName,
	COALESCE(o.total_sales_o, 0) [2025 Sales],
	COALESCE(oa.total_sales_oa, 0) [2024 Sales],
	COALESCE(o.total_sales_o, 0) - COALESCE(oa.total_sales_oa , 0) yoy_Change
FROM Sales.Customers c
LEFT JOIN ActiveSpend o
ON o.CustomerID = c.CustomerID
LEFT JOIN ArchiveSpend oa
ON oa.CustomerID = c.CustomerID

/*
	Business Scenario: Supply chain operations wants to evaluate each product's total units sold alongside its average shipping delay in days.

	TASK: For every product, display its total units sold alongside its average shipping time in days.
*/
WITH ProductsSold AS (
SELECT
	ProductID,
	SUM(Quantity) total_units_sold
FROM Sales.Orders
GROUP BY ProductID
)
, ShippingDays AS(
SELECT
	ProductID,
	AVG(DATEDIFF(DAY, OrderDate, ShipDate)) Avg_Ship_Time
FROM Sales.Orders
GROUP BY ProductID
)
SELECT 
	p.*,
	COALESCE(ps.total_units_sold, 0) Units_Sold,
	COALESCE(sd.Avg_Ship_Time, 0) Average_Shipping_Time
FROM Sales.Products p
LEFT JOIN ProductsSold ps
ON ps.ProductID = p.ProductID
LEFT JOIN ShippingDays sd
ON sd.ProductID = p.ProductID

/*
	TASK: Compare each department's total payroll cost against the total sales revenue generated by its employees, including the revenue-to-payroll ratio.
*/

WITH DeptPayroll AS
(
	SELECT 
		Department,
		SUM(Salary) total_payroll,
		COUNT(EmployeeID) head_count
	FROM Sales.Employees
	GROUP BY Department
)
, DeptRevenue AS (
	SELECT
		e.Department,
		SUM(o.Sales)  total_revenue
	FROM Sales.Orders o
	LEFT JOIN Sales.Employees e
	ON e.EmployeeID = o.SalesPersonID
	GROUP BY e.Department
)
SELECT 
	dp.Department,
	dp.head_count,
	COALESCE(dp.total_payroll, 0) [Total Payroll],
	COALESCE(dr.total_revenue, 0) [Total Revenue],
	ROUND(CAST(dp.total_payroll AS FLOAT) / NULLIF(dr.total_revenue, 0), 2) roi_Ratio
FROM DeptPayroll dp
LEFT JOIN DeptRevenue dr
ON dp.Department = dr.Department