/* WINDOWS RANKING FUNCTIOS
THERE ARE TWO TYPE FOR WINDOWS RANKING FUNCTION 
1. INTERGER BASED RANKING 
2. PERCENTAGE BASED RANKING

1. INTEGER BASED RANKING :
	- ROW_NUMBER()  -|
	- RANK()		 | - THESE FUNCTION DIDNT HAVE ANYTHING INIT
	- DENSE_RANK()	-|	
	- NTILE() -> THIS FUNCTION HAS NUMERIC VALUE IN IT
	
2. PERCENTAGE BASED RANKING :
	- CUME_DIST() -> CUMMULATIVE DISTRIBUTION
	- PERCENT_RANK() -> RELATIVE POSIITION
*/

-- ROW_NUMBER() : IT ASSIGN UNIQUE NUMBER TO THE ROWS IRRESPECTIVR OF DUPLICATES, BCOS IT DIDNT HANDLE TIES

-- TASK 1: GIVE THE RANK IN ORDER TABLE FOR SALES MAXIMUM TO MINIMUM

SELECT 
	OrderID,
	OrderDate,
	Sales,
	ROW_NUMBER() OVER(ORDER BY Sales DESC) SalesRank
FROM Sales.Orders;

-- TASK 2: GIVE THE UNIQUE IDENTIFICATION NUMBER TO OrdersArchive TABLE 

SELECT
	ROW_NUMBER() OVER(ORDER BY OrderID) UniqueID,
	*
FROM Sales.OrdersArchive

-- TASK 3: GET THE NON DUPLICATE VALUES FROM ORDERS TABLE

SELECT *
FROM (
	SELECT 
		ROW_NUMBER() OVER(PARTITION BY OrderID ORDER BY CreationTime DESC) UNIQUE_ROW,
		*	
	FROM Sales.OrdersArchive
)t
WHERE UNIQUE_ROW = 1

-- TASK 4: FIND THE TOP HIGHEST FOR EACH PRODUCT

SELECT *
FROM (
	SELECT
		OrderID,
		ProductID,
		Sales,
		ROW_NUMBER() OVER(PARTITION BY ProductID ORDER BY Sales DESC) ProductRANK
	FROM Sales.Orders
)t WHERE ProductRANK = 1

-- TASK 5: FINDING LOWEST 2 Customer TOTAL SALES

SELECT *
FROM(
	SELECT 
		CustomerID,
		SUM(Sales) TotalSales,
		ROW_NUMBER() OVER(ORDER BY SUM(Sales) ASC) AS SalesRank
	FROM Sales.Orders
	GROUP BY CustomerID
)t WHERE SalesRank <= 2

-- RANK() : IT ASSIGN A RANK TO EACH ROWS BUT GIVES SAME RANK FOR DUPLICATE COLUMNS,BUT IT LEAVES A GAP IN RANKING 

-- TASK 1: GIVE THE RANK IN ORDER TABLE FOR SALES MAXIMUM TO MINIMUM

SELECT 
	OrderID,
	OrderDate,
	Sales,
	RANK() OVER(ORDER BY Sales DESC) AS SalesRank
FROM Sales.Orders

-- TASK 2: GET THE DUPLICATE DATA PRESENT IN OrdersArchive TABLE 

SELECT 
	OrderID,
	OrderDate,
	Sales,
	RANK() OVER(ORDER BY OrderID ) AS SalesRank
FROM Sales.OrdersArchive

-- DENSE_RANK() : IT IS SAME AS RANK BUT IF DOES NOT LEAVES GAP IN RANKING

-- TASK 1: GIVE THE RANK IN ORDER TABLE FOR SALES MAXIMUM TO MINIMUM

SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	DENSE_RANK() OVER(ORDER BY Sales DESC) SalesRank
FROM Sales.Orders

-- TASK 2: GET THE DUPLICATE DATA PRESENT IN OrdersArchive TABLE 

SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	DENSE_RANK() OVER(ORDER BY OrderID ) AS CheckDuplicate
FROM Sales.OrdersArchive

-- NTILE() : IT DIVIDES A BIG GROUP INTO SPECIFIC NUMBER OF APPROXIMATE EQUAL GROUPS (BUCKETS)

SELECT 
	OrderID,
	OrderDate,
	Sales,
	NTILE(1) OVER(ORDER BY Sales DESC) BucketsONE,
	NTILE(2) OVER(ORDER BY Sales DESC) BucketsTWO,
	NTILE(3) OVER(ORDER BY Sales DESC) BucketsTHREE,
	NTILE(4) OVER(ORDER BY Sales DESC) BucketsFOUR
FROM Sales.Orders
