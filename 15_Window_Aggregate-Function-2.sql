-- MOVING AVERAGE
-- ITS JUST ALIKE RUNNING FUNCTION BUT WHEN CONDITION APPLIED IT MAY BECOME ROLLING

-- TASK 1: FIND THEN AVERAGE OF THE SALES ALONG WITH THE PREVIOUS ALL SALES

SELECT -- RUNNING
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	AVG(Sales) OVER(ORDER BY OrderDate) totalAverage, -- DEFAULT
	AVG(Sales) OVER(ORDER BY OrderDate ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS TOTAL_AVG -- FULL FORM
FROM Sales.Orders

-- TASK 2: FIND THE AVERAGE OF THE SALES ALONG WITH THE NEXT 2 SALES DATA ONLY 

SELECT -- ROLLING
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	AVG(Sales) OVER(ORDER BY OrderDate ROWS BETWEEN CURRENT ROW AND 2 FOLLOWING) AS AVERAGE
FROM Sales.Orders

-- TASK 3: FIND THE AVERAGE OF THE SALES ALONG WITH THE PREVIOUS 2 SALES DATA ONLY 

SELECT
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	AVG(Sales) OVER(ORDER BY OrderDate ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS [TOTAL AVERAGE], -- full
	AVG(Sales) OVER(ORDER BY OrderDate ROWS  2 PRECEDING) total_average -- short
FROM Sales.Orders

-- TASK 4: FIND THE AVERAGE OF THE SALES ALONG WITH THE PREVIOUS ALL SALES WRT DISTINCT ORDERSTATUS

SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	AVG(Sales) OVER(PARTITION BY OrderStatus ORDER BY OrderDate) AS average, -- Default
	AVG(Sales) OVER(PARTITION BY OrderStatus ORDER BY OrderDate ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)
FROM Sales.Orders

-- TASK 5:  FIND THE AVERAGE OF THE SALES ALONG WITH THE NEXT 2 SALES DATA ONLY WRT DISTINCT ORDERSTATUS

SELECT
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	AVG(Sales) OVER(PARTITION BY OrderStatus ORDER BY OrderDate 
		 ROWS BETWEEN CURRENT ROW AND 2 FOLLOWING ) AS totalSales
FROM Sales.Orders

-- TASK 6: FIND THE AVERAGE OF THE SALES ALONG WITH THE PREVIOUS 2 SALES DATA ONLY WRT DISTINCT ORDERSTATUS

SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	AVG(Sales) OVER(PARTITION BY OrderStatus ORDER BY OrderDate ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS totalSales 
FROM Sales.Orders

-- TASK 7: FIND THE AVERAGE OF THE SALES ALONG WITH THE PREVIOUS ALL(UNBOUNDED PRECEDING) AND NEXT ALL(INBOUNDED FOLLOWING) SALES 
SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	AVG(Sales) OVER(ORDER BY OrderDate ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS total_Sales 
	-- SAME AS : AVG(Sales) OVER() AS AVERAGE
FROM Sales.Orders

-- TASK 8: FIND THE AVERAGE OF THE SALES ALONG WITH THE PREVIOUS ALL(UNBOUNDED PRECEDING) AND NEXT ALL(INBOUNDED FOLLOWING) SALES WRT DISTINCT ORDERSTATUS

SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	AVG(Sales) OVER(PARTITION BY OrderStatus ORDER BY OrderDate ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS total_Sales 
	-- SAME AS : AVG(Sales) OVER(PARTITION BY OrderStatus ) AS AVERAGE
FROM Sales.Orders