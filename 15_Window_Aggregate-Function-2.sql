-- MIN() : IT RETURNS THE LOWEST VALUE WITHIN THE WINDOW 

-- TASK 1: FIND THE MINIMUM SALES IN ORDERS TABLE
SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	MIN(Sales) OVER() AS MinimumSales
FROM Sales.Orders

-- TASK 2: FIND THE MINIMUM SALES IN ORDERS TABLE WITH RESPECT TO DISTINCT PRODUCTS

SELECT
	p.Product,
	p.ProductID,
	o.OrderID,
	o.OrderDate,
	o.OrderStatus,
	Sales,
	MIN(Sales) OVER(PARTITION BY o.ProductID) AS MinimumSalesByProduct
FROM Sales.Orders o
LEFT JOIN Sales.Products p
ON o.ProductID = p.ProductID

-- TASK 3: FIND THE MIN DEAVIATION WRT ALL ORDERS

SELECT 
	OrderID,
	OrderDate,
	ProductID,
	Sales,
	MIN(Sales) OVER() AS MinimumSales,
	Sales - MIN(Sales) OVER() AS Min_Deviation
FROM Sales.Orders

-- TASK 4: FIND THE MIN DEAVIATION WRT ALL ORDERS WITH RESPECT TO DISTINCT ORDERSTATUS

SELECT
	OrderID,
	OrderDate,
	OrderStatus,
	ProductID,
	Sales,
	MIN(Sales) OVER(PARTITION BY OrderStatus) AS MinSales_WRTProduct,
	Sales - MIN(Sales) OVER(PARTITION BY OrderStatus) AS Min_Deviation_WRTProduct
FROM Sales.Orders

-- MAX(): IT RETURNS THE HIGHEST VALUE WITHIN THE WINDOW

-- TASK 1: FIND THE MAXIMUM SALES IN ORDERS TABLE
SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	MAX(Sales) OVER() AS MaximumSales
FROM Sales.Orders

-- TASK 2: FIND THE MAXIMUM SALES IN ORDERS TABLE WITH RESPECT TO DISTINCT PRODUCT

SELECT
	p.Product,
	p.ProductID,
	o.OrderID,
	o.OrderDate,
	o.OrderStatus,
	Sales,
	MAX(Sales) OVER(PARTITION BY o.ProductID) AS MaximumSalesByProduct
FROM Sales.Orders o
LEFT JOIN Sales.Products p
ON o.ProductID = p.ProductID

-- TASK 3: FIND THE MAX DEAVIATION WRT ALL ORDERS

SELECT 
	OrderID,
	OrderDate,
	ProductID,
	Sales,
	MAX(Sales) OVER() AS MaximumSales,
	ABS(Sales - MAX(Sales) OVER()) AS Max_Deviation_ABS,
	MAX(Sales) OVER() - Sales  AS Max_Deviation
FROM Sales.Orders

-- TASK 4: FIND THE MAX DEAVIATION WRT ALL ORDERS WITH RESPECT TO DISTINCT ORDERSTATUS

SELECT
	OrderID,
	OrderDate,
	OrderStatus,
	ProductID,
	Sales,
	MAX(Sales) OVER(PARTITION BY OrderStatus) AS MaxSales_WRTProduct,
	ABS(Sales - MAX(Sales) OVER(PARTITION BY OrderStatus)) AS Max_Deviation_WRTProductABS,
	MAX(Sales) OVER(PARTITION BY OrderStatus) - Sales  AS Max_Deviation_WRTProduct
FROM Sales.Orders

-- RUNNING TOTAL & ROLLING TOTAL
-- IT IS THE AGGREAGATED SEQUENCE OF MEMBERS AND THE AGGREGATION IS UPDATED EACH TIME WHEN A NEW MEMBER IS ADDED 

-- RUNNING TOTAL : IT  AGGREGATES ALL VALUE FROM BEGINNING UP TO CURRENT POINT WITHOUT DROPING OFF OLDER DATA.
-- FRAME USED: DEFAULT (ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)

-- TASK 1: FIND THEN SUM OF THE SALES ALONG WITH THE PREVIOUS ALL SALES

SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	SUM(Sales) OVER(ORDER BY OrderDate ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS totalSalesFULL,
	SUM(Sales) OVER(ORDER BY OrderDate ROWS UNBOUNDED PRECEDING) AS totalSalesSHORT,
	SUM(Sales) OVER(ORDER BY OrderDate) AS Total_SalesDefault
	-- here all these 3 forms will give same result preferr last one in case of rolling function
FROM Sales.Orders

-- TASK 2: FIND THE SUM OF THE SALES ALONG WITH THE PREVIOUS ALL SALES WRT DISTINCT ORDERSTATUS

SELECT
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	SUM(Sales) OVER( PARTITION BY ORDERSTATUS ORDER BY OrderDate ) AS totalSales
FROM Sales.Orders

-- ROLLING TOTAL :IT AGGREGATES ALL THE VALUES WITHIN A FIX TIME WINDOW, AND AS NEW DATA IS ADDED OLD POINT WILL BE DROPPED BASED ON THE CONDITION

-- TASK 1: FIND THE SUM OF THE SALES ALONG WITH THE PREVIOUS 2 SALES DATA ONLY 

SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	SUM(Sales) OVER(ORDER BY OrderDate ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS total_Sales
FROM Sales.Orders

-- TASK 2: FIND THE SUM OF THE SALES ALONG WITH THE PREVIOUS 2 SALES DATA ONLY WRT DISTINCT ORDERSTATUS

SELECT 
	OrderID,
	OrderDate,
	OrderStatus,
	Sales,
	SUM(Sales) OVER(PARTITION BY OrderStatus ORDER BY OrderDate 
					ROWS BETWEEN 2 PRECEDING AND CURRENT ROW )
FROM Sales.Orders
